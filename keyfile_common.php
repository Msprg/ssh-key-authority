/**
 * Generation of the authorized-keys files that are written to /var/local/keys-sync/<account> on target servers,
 * and the rules behind it: which access rules apply to an account, and whose keys a rule lets in.
 *
 * Shared by scripts/sync.php, which writes the files, by the "Troubleshoot access" tool, which shows the admin
 * what would be written and why, by the permissions report, and by the list of inherited rules on the server
 * and account pages (ServerAccount::list_inherited_access()). All of them must go through this one
 * implementation, so that none of them can say something that the sync does not do.
 */

require_once(__DIR__.'/history_username_env_common.php');

const KEYFILE_HEADER = "## Auto generated keys file for %s
## Do not edit this file! Modify at %s
";

/**
 * What the functions below have looked up so far in this process: the rules of groups and the members of the
 * groups that rules name. Many accounts share the same few groups, so this saves most of the work of a report.
 *
 * Nothing in here is ever refreshed. That is fine for the callers there are - a sync of one server, the
 * rendering of one page - but these functions must not be relied on after members or rules were changed in
 * the same process without calling forget_access_rule_cache() in between. The Access and entity objects that
 * they return are shared between calls: treat them as read-only.
 */
function &access_rule_cache() {
	static $cache = array('rules' => array(), 'members' => array());
	return $cache;
}

/**
 * Drop everything that was remembered about rules and group members, see access_rule_cache().
 */
function forget_access_rule_cache() {
	$cache = &access_rule_cache();
	$cache = array('rules' => array(), 'members' => array());
}

/**
 * Tell whether an account is one that the sync builds a key file for. Accounts that were removed from SKA, or
 * that so far only exist as part of an access request, are not.
 *
 * This looks at the account alone. Which file that is, and whether the server gets key files at all, is the
 * business of list_keyfile_accounts().
 */
function account_gets_keyfile(ServerAccount $account) {
	return $account->active != 0 && $account->sync_status != 'proposed';
}

/**
 * List the managed accounts that the sync writes key files for on a server, by the name of their key file.
 *
 * The file name is the account name without slashes. If several accounts end up with the same file name, the
 * last one gets the file. There is never a file for "keys-sync": that is the account SKA itself logs in with,
 * and its key file is set up by hand. A server whose keys are not managed by SKA gets no files at all.
 *
 * @param Server $server The server to list the accounts of
 * @return array file name => ServerAccount
 */
function list_keyfile_accounts(Server $server) {
	$accounts = array();
	if($server->key_management != 'keys') {
		return $accounts;
	}
	foreach($server->list_accounts() as $account) {
		if(!account_gets_keyfile($account)) continue;
		$accounts[str_replace('/', '', $account->name)] = $account;
	}
	unset($accounts['keys-sync']);
	return $accounts;
}

/**
 * List what the access rules for an account hang on, in the order in which the sync writes their keys: the
 * groups that the account is a member of, directly or through other groups, and then the account itself.
 * A group that is reached in more than one way is listed (and written) as often.
 *
 * A group counts even if the account is in it only through an inactive group; 'in_effect' is about the rules
 * of each group itself. Whether the account gets a key file at all is not looked at here, see
 * list_keyfile_accounts().
 *
 * Group rules are remembered, see access_rule_cache(): a report asks for the same few groups (such as
 * "root-accounts") once per account of every server.
 *
 * @param ServerAccount $account The account to list the rule sets of
 * @return array of array('target' => Group|ServerAccount, 'in_effect' => bool, 'rules' => array of Access).
 *               The rules of an inactive group are not in effect: the sync leaves them out.
 */
function list_account_rule_sets(ServerAccount $account) {
	$cache = &access_rule_cache();
	$sets = array();
	foreach($account->list_group_membership() as $group) {
		if(!isset($cache['rules'][$group->id])) {
			$cache['rules'][$group->id] = $group->list_access();
		}
		$sets[] = array('target' => $group, 'in_effect' => $group->active != 0, 'rules' => $cache['rules'][$group->id]);
	}
	$sets[] = array('target' => $account, 'in_effect' => true, 'rules' => $account->list_access());
	return $sets;
}

/**
 * Work out whose keys an access rule lets in, given what the rule was granted to.
 *
 * A user or a server account stands for itself. A group stands for its members, and the groups among them for
 * theirs; each group is taken once, by name, so that groups containing each other end somewhere. Only the
 * group that the rule names has to be active: an inactive group is not expanded, but an inactive group further
 * down is. Somebody who is reached in several ways appears as often.
 *
 * These are the rules of the sync, oddities included. A caller that wants something else (no duplicates,
 * say) has to filter the result, not expand differently.
 *
 * The members of a group are remembered, see access_rule_cache(), as many accounts share the same rules.
 *
 * @param Entity $source The user, server account or group that the rule grants access to
 * @param bool $even_if_inactive Expand a group although it is inactive, to tell whom the rule would cover
 * @return array a node: array('entity' => User|ServerAccount), or array('group' => Group, 'expanded' => bool,
 *               'members' => array of nodes); an empty array for anything else
 */
function expand_access_source(Entity $source, $even_if_inactive = false) {
	$cache = &access_rule_cache();
	switch(get_class($source)) {
	case 'User':
	case 'ServerAccount':
		return array('entity' => $source);
	case 'Group':
		if(!$source->active && !$even_if_inactive) {
			return array('group' => $source, 'expanded' => false, 'members' => array());
		}
		if(!isset($cache['members'][$source->id])) {
			$seen = array($source->name => true);
			$cache['members'][$source->id] = expand_group_members($source->list_members(), $seen);
		}
		return array('group' => $source, 'expanded' => true, 'members' => $cache['members'][$source->id]);
	}
	return array();
}

/**
 * Expand the members of a group for expand_access_source().
 *
 * @param array $entities Members of the group (User, ServerAccount and Group objects)
 * @param array &$seen Names of the groups that have been expanded so far, as keys
 * @return array of nodes, see expand_access_source()
 */
function expand_group_members(array $entities, array &$seen) {
	$nodes = array();
	foreach($entities as $entity) {
		switch(get_class($entity)) {
		case 'User':
		case 'ServerAccount':
			$nodes[] = array('entity' => $entity);
			break;
		case 'Group':
			if(!isset($seen[$entity->name])) {
				$seen[$entity->name] = true;
				$nodes[] = array('group' => $entity, 'expanded' => true, 'members' => expand_group_members($entity->list_members(), $seen));
			}
			break;
		}
	}
	return $nodes;
}

/**
 * List the users and server accounts that a node of expand_access_source() stands for, in the order in which
 * their keys are written.
 *
 * @param array $node A node as returned by expand_access_source()
 * @param array $via Groups passed on the way to this node, for use in the recursion
 * @return array of array('entity' => User|ServerAccount, 'via' => array of Group: the groups below the one that
 *               the rule names through which this member is reached, outermost first)
 */
function list_access_grantees(array $node, array $via = array()) {
	if(isset($node['entity'])) {
		return array(array('entity' => $node['entity'], 'via' => $via));
	}
	$grantees = array();
	foreach($node['members'] ?? array() as $member) {
		foreach(list_access_grantees($member, isset($member['group']) ? array_merge($via, array($member['group'])) : $via) as $grantee) {
			$grantees[] = $grantee;
		}
	}
	return $grantees;
}

/**
 * Build the content of the key file of a managed server account, exactly as the sync writes it.
 *
 * @param Server $server The server that the account lives on
 * @param ServerAccount $account The account to build the key file for
 * @return string content of /var/local/keys-sync/<account name>
 */
function build_account_keyfile(Server $server, ServerAccount $account) {
	global $config;
	$comment = (int)$config['privacy']['comment_key_files'];
	$hostname = $server->hostname;
	$keyfile = sprintf(KEYFILE_HEADER, "account '{$account->name}'", $config['web']['baseurl']."/servers/".urlencode($hostname)."/accounts/".urlencode($account->name));
	foreach(list_account_rule_sets($account) as $set) {
		$target = $set['target'];
		$is_group = get_class($target) == 'Group';
		if(!$set['in_effect']) continue; // Rules for inactive groups should be ignored
		if($is_group && $comment == 1) {
			$keyfile .= "# === Start of rules applied due to membership in {$target->name} group ===\n";
		}
		$keyfile .= get_keys($set['rules'], $account->name, $hostname, $comment, $server);
		if($is_group && $comment == 1) {
			$keyfile .= "# === End of rules applied due to membership in {$target->name} group ===\n\n";
		}
	}
	return $keyfile;
}

/**
 * Build the option prefix that the key lines of LDAP users get on a server with LDAP authorization.
 *
 * @param Server $server The server to read the LDAP access options of
 * @return string the options followed by a space, or an empty string if there are none
 */
function get_ldap_access_option_prefix(Server $server) {
	$optiontext = array();
	foreach($server->list_ldap_access_options() as $option) {
		$optiontext[] = $option->option.(is_null($option->value) ? '' : '="'.str_replace('"', '\\"', $option->value).'"');
	}
	$prefix = implode(',', $optiontext);
	if($prefix !== '') $prefix .= ' ';
	return $prefix;
}

/**
 * Build the content of the key file that an LDAP user gets on a server with LDAP authorization, exactly as
 * the sync writes it. Such a file holds the user's own keys only; access rules play no role for it.
 *
 * @param Server $server The server that the file is for
 * @param User $user The user to build the key file for
 * @param string|null $prefix Result of get_ldap_access_option_prefix() if already known, to save the lookup
 * @return string|null content of /var/local/keys-sync/<uid>, or null if the user has no key for this server
 *                     and therefore gets no file
 */
function build_ldap_user_keyfile(Server $server, User $user, $prefix = null) {
	global $config;
	$comment = (int)$config['privacy']['comment_key_files'];
	if(is_null($prefix)) {
		$prefix = get_ldap_access_option_prefix($server);
	}
	$username = str_replace('/', '', $user->uid);
	$keyfile = sprintf(KEYFILE_HEADER, "LDAP user '{$user->uid}'", $config['web']['baseurl']);
	$keys = $user->list_public_keys($username, $server->hostname, false);
	if(count($keys) == 0) {
		return null;
	}
	if($user->active) {
		$user_prefix = add_user_history_username_env_option($prefix, $user, $server);
		foreach($keys as $key) {
			$keyfile .= $user_prefix.$key->export_userkey_with_fixed_comment($user, $comment)."\n";
		}
	} elseif ($comment == 1) {
		$keyfile .= "# Account disabled\n";
	}
	return $keyfile;
}

function get_default_history_username_env_format() {
	return 'BASH_HISTORY_USERNAME={uid}';
}

function history_username_env_value_is_valid($value) {
	if($value === '') {
		return false;
	}
	if(preg_match('/[\r\n,\'"\\\\{}]/', $value)) {
		return false;
	}
	return preg_match('/^[A-Za-z0-9 ._@:+=-]+$/', $value) === 1;
}

function normalize_history_username_env_format($format) {
	$format = trim((string)$format);
	if(!history_username_env_format_is_valid($format)) {
		return get_default_history_username_env_format();
	}
	return $format;
}

function get_global_history_username_env_enabled() {
	global $config;
	if(!isset($config['privacy']) || !isset($config['privacy']['history_username_env_default'])) {
		return false;
	}
	return intval($config['privacy']['history_username_env_default']) === 1;
}

function get_global_history_username_env_format() {
	global $config;
	if(isset($config['privacy']) && isset($config['privacy']['history_username_env_format'])) {
		return normalize_history_username_env_format($config['privacy']['history_username_env_format']);
	}
	return get_default_history_username_env_format();
}

function get_server_history_username_env_mode($server) {
	try {
		$mode = $server->history_username_env_mode;
	} catch(Exception $e) {
		return 'inherit';
	}
	if($mode !== 'enabled' && $mode !== 'disabled') {
		return 'inherit';
	}
	return $mode;
}

function get_server_history_username_env_enabled($server) {
	$mode = get_server_history_username_env_mode($server);
	switch($mode) {
	case 'enabled':
		return true;
	case 'disabled':
		return false;
	default:
		return get_global_history_username_env_enabled();
	}
}

function get_server_history_username_env_format($server) {
	try {
		$format = trim((string)$server->history_username_env_format);
	} catch(Exception $e) {
		$format = '';
	}
	if($format !== '') {
		return normalize_history_username_env_format($format);
	}
	return get_global_history_username_env_format();
}

function escape_authorized_keys_option_value($value) {
	$value = preg_replace('/[[:cntrl:]]+/', '', (string)$value);
	if($value === null) {
		$value = '';
	}
	if(!history_username_env_value_is_valid($value)) {
		throw new InvalidArgumentException('Invalid history username environment value');
	}
	return str_replace(array('\\', '"'), array('\\\\', '\\"'), $value);
}

function append_authorized_keys_option($prefix, $option) {
	$prefix = trim((string)$prefix);
	if($prefix === '') {
		return $option.' ';
	}
	return rtrim($prefix, ',').','.$option.' ';
}

function get_user_history_username_env_option($user, $server) {
	if(!get_server_history_username_env_enabled($server)) {
		return null;
	}
	$value = str_replace('{uid}', $user->uid, get_server_history_username_env_format($server));
	if(!history_username_env_value_is_valid($value)) {
		return null;
	}
	try {
		return 'environment="'.escape_authorized_keys_option_value($value).'"';
	} catch(InvalidArgumentException $e) {
		return null;
	}
}

function add_user_history_username_env_option($prefix, $user, $server) {
	$option = get_user_history_username_env_option($user, $server);
	if(is_null($option)) {
		return $prefix;
	}
	return append_authorized_keys_option($prefix, $option);
}

function append_user_keys($keyfile, $entity, $prefix, $account_name, $hostname, $comment, $server, $grant_details = null) {
	if ($comment == 1) {
		$keyfile .= "# {$entity->uid}";
		if (!is_null($grant_details)) {
			$keyfile .= " {$grant_details}";
		}
		$keyfile .= "\n";
	}
	if($entity->active) {
		$prefix = add_user_history_username_env_option($prefix, $entity, $server);
		$keys = $entity->list_public_keys($account_name, $hostname, false);
		foreach($keys as $key) {
			$keyfile .= $prefix.$key->export_userkey_with_fixed_comment($entity, $comment)."\n";
		}
	} elseif ($comment == 1) {
		$keyfile .= "# Account disabled\n";
	}
	return $keyfile;
}

function append_serveraccount_keys($keyfile, $entity, $prefix, $account_name, $hostname, $comment, $grant_details = null) {
	if ($comment == 1) {
		$keyfile .= "# {$entity->name}@{$entity->server->hostname}";
		if (!is_null($grant_details)) {
			$keyfile .= " {$grant_details}";
		}
		$keyfile .= "\n";
	}
	if($entity->server->key_management != 'decommissioned') {
		$keys = $entity->list_public_keys($account_name, $hostname, false);
		foreach($keys as $key) {
			$keyfile .= $prefix.$key->export_serverkey_with_fixed_comment($entity, $comment)."\n";
		}
	} elseif ($comment == 1) {
		$keyfile .= "# Decommissioned server\n";
	}
	return $keyfile;
}

function get_keys($access_rules, $account_name, $hostname, $comment, $server) {
	$keyfile = '';
	foreach($access_rules as $access) {
		$grant_date = new DateTime($access->grant_date);
		$grant_date_full = $grant_date->format('c');
		$entity = $access->source_entity;
		$optiontext = array();
		foreach($access->list_options() as $option) {
			$optiontext[] = $option->option.(is_null($option->value) ? '' : '="'.str_replace('"', '\\"', $option->value).'"');
		}
		$prefix = implode(',', $optiontext);
		if($prefix !== '') $prefix .= ' ';
		$node = expand_access_source($entity);
		if(isset($node['entity'])) {
			$keyfile = append_entity_keys(
				$keyfile,
				$node['entity'],
				$prefix,
				$account_name,
				$hostname,
				$comment,
				$server,
				"granted access by {$access->granted_by->uid} on {$grant_date_full}"
			);
		} elseif(isset($node['group'])) {
			if ($comment == 1) {
				$keyfile .= "# {$entity->name} group";
				$keyfile .= " granted access by {$access->granted_by->uid} on {$grant_date_full}";
				$keyfile .= "\n";
			}
			if($node['expanded']) {
				if ($comment == 1) {
					$keyfile .= "# == Start of {$entity->name} group members ==\n";
				}
				$keyfile .= get_group_keys($node['members'], $account_name, $hostname, $prefix, $comment, $server);
				if ($comment == 1) {
					$keyfile .= "# == End of {$entity->name} group members ==\n";
				}
			} elseif ($comment == 1) {
				$keyfile .= "# Inactive group\n";
			}
		}
	}
	return $keyfile;
}

/**
 * Write the key lines of one user or server account.
 */
function append_entity_keys($keyfile, $entity, $prefix, $account_name, $hostname, $comment, $server, $grant_details = null) {
	if(get_class($entity) == 'User') {
		return append_user_keys($keyfile, $entity, $prefix, $account_name, $hostname, $comment, $server, $grant_details);
	}
	return append_serveraccount_keys($keyfile, $entity, $prefix, $account_name, $hostname, $comment, $grant_details);
}

/**
 * Write the key lines of the members of a group.
 *
 * @param array $nodes The members, as nodes of expand_access_source()
 */
function get_group_keys($nodes, $account_name, $hostname, $prefix, $comment, $server) {
	$keyfile = '';
	foreach($nodes as $node) {
		if(isset($node['entity'])) {
			$keyfile = append_entity_keys($keyfile, $node['entity'], $prefix, $account_name, $hostname, $comment, $server);
		} elseif(isset($node['group'])) {
			$group = $node['group'];
			if ($comment == 1) {
				$keyfile .= "# {$group->name} group";
				$keyfile .= "\n";
				$keyfile .= "# == Start of {$group->name} group members ==\n";
			}
			$keyfile .= get_group_keys($node['members'], $account_name, $hostname, $prefix, $comment, $server);
			if ($comment == 1) {
				$keyfile .= "# == End of {$group->name} group members ==\n";
			}
		}
	}
	return $keyfile;
}
